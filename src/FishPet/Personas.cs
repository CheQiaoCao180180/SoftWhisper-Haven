    internal static readonly string[] Names = Array.ConvertAll(All, one => one.Name);

    internal static Persona Of(string? name)
    {
        foreach (var one in All)
            if (one.Name == name) return one;
        return All[0];
    }

    internal static bool Known(string? name) => Array.IndexOf(Names, name) >= 0;

    /// <summary>循环切换用：返回下一个名字。</summary>
    internal static string Next(string? name)
    {
        var at = Array.IndexOf(Names, name);
        return Names[(at + 1 + Names.Length) % Names.Length];
    }
